use std::path::{Path, PathBuf};

use snafu::prelude::*;
pub use wasm2nix_ast as nix;
use wasm2nix_runtime::DEFAULT_RUNTIME_FILE_NAME;

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct TranspileOptions {
    pub runtime_import_expr: String,
    pub render_options: nix::RenderOptions,
}

impl TranspileOptions {
    #[must_use]
    pub fn new(runtime_import_expr: impl Into<String>) -> Self {
        Self {
            runtime_import_expr: runtime_import_expr.into(),
            render_options: nix::RenderOptions::default(),
        }
    }
}

impl Default for TranspileOptions {
    fn default() -> Self {
        Self::new(format!("./{DEFAULT_RUNTIME_FILE_NAME}"))
    }
}

/// Lowers a Wasm module to a complete Nix module wrapper.
///
/// # Errors
///
/// Returns an error when the Wasm bytes cannot be translated or when lowering
/// to the Nix AST fails.
pub fn lower_wasm_to_nix(wasm: &[u8], options: &TranspileOptions) -> error::Result<String> {
    let module = translator::NixModule::translate(wasm).context(error::TranslateWasmSnafu)?;
    let module = lower::lower_module(&module)
        .context(error::LowerNixSnafu)?
        .render_with(&options.render_options);
    let separator = if options.render_options.style == nix::RenderStyle::Compact {
        " "
    } else {
        "\n\n"
    };
    Ok(format!(
        "{{ imports ? {{ }}, rt ? import {} {{ }} }}:{separator}({module}) rt imports",
        options.runtime_import_expr
    ))
}

#[must_use]
pub fn generated_nix_file(
    input_path: Option<&Path>, nix_expr: &str, render_options: &nix::RenderOptions,
) -> String {
    if render_options.style == nix::RenderStyle::Compact {
        return format!("{nix_expr}\n");
    }

    input_path.map_or_else(
        || format!("# Generated by wasm2nix\n\n{nix_expr}\n"),
        |input_path| {
            format!(
                "# Generated by wasm2nix\n# input = {}\n\n{}\n",
                input_path.display(),
                nix_expr
            )
        },
    )
}

#[must_use]
pub fn default_output_path(input_path: &Path) -> PathBuf {
    let mut path = input_path.to_path_buf();
    path.set_extension("nix");
    path
}

#[must_use]
pub fn runtime_path_for_output(out_path: &Path, export_rt_path: Option<&Path>) -> PathBuf {
    match export_rt_path {
        Some(path) if path.is_absolute() => path.to_path_buf(),
        Some(path) => out_path
            .parent()
            .filter(|parent| !parent.as_os_str().is_empty())
            .unwrap_or_else(|| Path::new("."))
            .join(path),
        None => out_path.with_file_name(default_runtime_file_name(out_path)),
    }
}

#[must_use]
pub fn runtime_import_expr(
    out_path: &Path, export_rt_path: Option<&Path>, runtime_path: &Path,
) -> String {
    match export_rt_path {
        Some(path) if !path.is_absolute() => relative_nix_path_expr(path),
        None => relative_nix_path_expr(Path::new(&default_runtime_file_name(out_path))),
        _ => nix_path_expr(runtime_path),
    }
}

fn default_runtime_file_name(out_path: &Path) -> String {
    let stem = out_path
        .file_stem()
        .and_then(|stem| stem.to_str())
        .filter(|stem| !stem.is_empty())
        .unwrap_or("wasm2nix");
    format!("{stem}-rt.nix")
}

fn nix_path_expr(path: &Path) -> String {
    if path.is_absolute() {
        path.display().to_string()
    } else {
        relative_nix_path_expr(path)
    }
}

fn relative_nix_path_expr(path: &Path) -> String {
    let path = path.display().to_string();
    if path.starts_with("./") || path.starts_with("../") {
        path
    } else {
        format!("./{path}")
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn generated_nix_imports_default_runtime() {
        let wasm = [
            0x00, 0x61, 0x73, 0x6D, 0x01, 0x00, 0x00, 0x00, 0x01, 0x04, 0x01, 0x60, 0x00, 0x00,
            0x03, 0x02, 0x01, 0x00, 0x0A, 0x04, 0x01, 0x02, 0x00, 0x0B,
        ];

        let nix =
            lower_wasm_to_nix(&wasm, &TranspileOptions::default()).expect("wasm should lower");

        assert!(nix.starts_with("{ imports ? { }, rt ? import ./wasm2nix-rt.nix { } }:"));
        assert!(nix.ends_with(") rt imports"));
    }

    #[test]
    fn generated_file_omits_comments_in_compact_mode() {
        let render_options = nix::RenderOptions {
            style: nix::RenderStyle::Compact,
            ..nix::RenderOptions::default()
        };

        assert_eq!(
            generated_nix_file(Some(Path::new("input.wasm")), "expr", &render_options),
            "expr\n"
        );
    }

    #[test]
    fn default_runtime_path_uses_output_file_stem() {
        let out = Path::new("dist/module.nix");

        assert_eq!(
            runtime_path_for_output(out, None),
            PathBuf::from("dist/module-rt.nix")
        );
        assert_eq!(
            runtime_import_expr(out, None, &runtime_path_for_output(out, None)),
            "./module-rt.nix"
        );
    }

    #[test]
    fn relative_export_rt_path_is_relative_to_output_dir_and_import() {
        let out = Path::new("dist/module.nix");
        let export = Path::new("rt/custom.nix");

        assert_eq!(
            runtime_path_for_output(out, Some(export)),
            PathBuf::from("dist/rt/custom.nix")
        );
        assert_eq!(
            runtime_import_expr(
                out,
                Some(export),
                &runtime_path_for_output(out, Some(export))
            ),
            "./rt/custom.nix"
        );
    }

    #[test]
    fn absolute_export_rt_path_is_imported_as_absolute_path() {
        let out = Path::new("dist/module.nix");
        let export = Path::new("/tmp/wasm2nix-rt.nix");

        assert_eq!(
            runtime_path_for_output(out, Some(export)),
            PathBuf::from("/tmp/wasm2nix-rt.nix")
        );
        assert_eq!(
            runtime_import_expr(
                out,
                Some(export),
                &runtime_path_for_output(out, Some(export))
            ),
            "/tmp/wasm2nix-rt.nix"
        );
    }
}
