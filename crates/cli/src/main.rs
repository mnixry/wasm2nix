use std::path::{Path, PathBuf};

use clap::Parser;
use snafu::prelude::*;
use wasm2nix::{error, lower_wasm_to_nix};
use wasm2nix_runtime::runtime_nix;

#[derive(Debug, Clone, Parser)]
struct Args {
    /// Input `.wasm` file path.
    input: PathBuf,

    /// Output `.nix` file path (defaults to input path with `.nix` extension).
    #[arg(short, long)]
    output: Option<PathBuf>,

    /// Do not write the runtime file next to the generated Nix file.
    #[arg(long)]
    no_export_rt: bool,

    /// Runtime file path to write and import from (relative paths are resolved
    /// from the output file directory).
    #[arg(long, value_name = "PATH")]
    export_rt_path: Option<PathBuf>,
}

#[snafu::report]
fn main() -> error::Result<()> {
    let args = Args::parse();

    let wasm = std::fs::read(&args.input).context(error::ReadWasmSnafu {
        path: args.input.clone(),
    })?;

    let out_path = if let Some(path) = args.output.clone() {
        path
    } else {
        let mut path = args.input.clone();
        path.set_extension("nix");
        path
    };

    let runtime_path = runtime_path_for_output(&out_path, args.export_rt_path.as_deref());
    let runtime_import =
        runtime_import_expr(&out_path, args.export_rt_path.as_deref(), &runtime_path);

    let nix_expr = lower_wasm_to_nix(&wasm, &runtime_import)?;
    let nix = format!(
        "# Generated by wasm2nix\n# input = {}\n\n{}\n",
        args.input.display(),
        nix_expr
    );

    if !args.no_export_rt {
        std::fs::write(&runtime_path, runtime_nix())
            .context(error::WriteNixSnafu { path: runtime_path })?;
    }

    std::fs::write(&out_path, nix).context(error::WriteNixSnafu { path: out_path })?;
    Ok(())
}

fn runtime_path_for_output(out_path: &Path, export_rt_path: Option<&Path>) -> PathBuf {
    match export_rt_path {
        Some(path) if path.is_absolute() => path.to_path_buf(),
        Some(path) => out_path
            .parent()
            .filter(|parent| !parent.as_os_str().is_empty())
            .unwrap_or_else(|| Path::new("."))
            .join(path),
        None => out_path.with_file_name(default_runtime_file_name(out_path)),
    }
}

fn runtime_import_expr(
    out_path: &Path, export_rt_path: Option<&Path>, runtime_path: &Path,
) -> String {
    match export_rt_path {
        Some(path) if !path.is_absolute() => relative_nix_path_expr(path),
        None => relative_nix_path_expr(Path::new(&default_runtime_file_name(out_path))),
        _ => nix_path_expr(runtime_path),
    }
}

fn default_runtime_file_name(out_path: &Path) -> String {
    let stem = out_path
        .file_stem()
        .and_then(|stem| stem.to_str())
        .filter(|stem| !stem.is_empty())
        .unwrap_or("wasm2nix");
    format!("{stem}-rt.nix")
}

fn nix_path_expr(path: &Path) -> String {
    if path.is_absolute() {
        path.display().to_string()
    } else {
        relative_nix_path_expr(path)
    }
}

fn relative_nix_path_expr(path: &Path) -> String {
    let path = path.display().to_string();
    if path.starts_with("./") || path.starts_with("../") {
        path
    } else {
        format!("./{path}")
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn default_runtime_path_uses_output_file_stem() {
        let out = Path::new("dist/module.nix");

        assert_eq!(
            runtime_path_for_output(out, None),
            PathBuf::from("dist/module-rt.nix")
        );
        assert_eq!(
            runtime_import_expr(out, None, &runtime_path_for_output(out, None)),
            "./module-rt.nix"
        );
    }

    #[test]
    fn relative_export_rt_path_is_relative_to_output_dir_and_import() {
        let out = Path::new("dist/module.nix");
        let export = Path::new("rt/custom.nix");

        assert_eq!(
            runtime_path_for_output(out, Some(export)),
            PathBuf::from("dist/rt/custom.nix")
        );
        assert_eq!(
            runtime_import_expr(
                out,
                Some(export),
                &runtime_path_for_output(out, Some(export))
            ),
            "./rt/custom.nix"
        );
    }

    #[test]
    fn absolute_export_rt_path_is_imported_as_absolute_path() {
        let out = Path::new("dist/module.nix");
        let export = Path::new("/tmp/wasm2nix-rt.nix");

        assert_eq!(
            runtime_path_for_output(out, Some(export)),
            PathBuf::from("/tmp/wasm2nix-rt.nix")
        );
        assert_eq!(
            runtime_import_expr(
                out,
                Some(export),
                &runtime_path_for_output(out, Some(export))
            ),
            "/tmp/wasm2nix-rt.nix"
        );
    }
}
