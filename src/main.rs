mod clif_to_nix;
mod error;
mod log;
mod nix;
mod translator;

use clap::Parser;
use std::path::PathBuf;

#[derive(Debug, Clone, Parser)]
#[command(name = "wasm2nix")]
#[command(about = "Transpile WebAssembly to a pure evaluation-time Nix module (WIP)")]
struct Args {
    /// Input `.wasm` file path.
    input: PathBuf,

    /// Output `.nix` file path (defaults to input path with `.nix` extension).
    #[arg(short, long)]
    output: Option<PathBuf>,

    /// Increase verbosity (-v, -vv, -vvv)
    #[arg(short, long, action = clap::ArgAction::Count)]
    verbose: u8,
}

#[snafu::report]
fn main() -> error::Result<()> {
    let args = Args::parse();

    let level = match args.verbose {
        0 => log::LogLevel::Info,
        1 => log::LogLevel::Debug,
        _ => log::LogLevel::Trace,
    };
    let logger = log::init_logger(level);

    let wasm = std::fs::read(&args.input).map_err(|source| error::Error::ReadWasm {
        path: args.input.clone(),
        source,
    })?;

    slog::info!(logger, "Read wasm"; "bytes" => wasm.len());

    let out_path = args.output.clone().unwrap_or_else(|| {
        let mut p = args.input.clone();
        p.set_extension("nix");
        p
    });

    let module =
        translator::NixModule::translate(&wasm).map_err(|e| error::Error::TranslateWasm {
            message: e.to_string(),
        })?;

    let nix_expr = clif_to_nix::lower_module(&module);
    let nix = format!(
        "# Generated by wasm2nix (WIP)\n# input = {}\n\n{}\n",
        args.input.display(),
        nix_expr.render()
    );

    std::fs::write(&out_path, nix).map_err(|source| error::Error::WriteNix {
        path: out_path.clone(),
        source,
    })?;
    slog::info!(logger, "Wrote nix output"; "path" => out_path.display().to_string());
    Ok(())
}
